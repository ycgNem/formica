/**
 * Pixel icons on a 10×10 grid, drawn at two screen pixels a cell so they share the chunky look of the sprites.
 * Each row is a string: `#` is a filled cell. Runs along a row become one rect.
 */
const px = (...rows: string[]): string => {
  let d = '';
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] !== '#') continue;
      let e = x;
      while (row[e + 1] === '#') e++;
      d += `M${x} ${y}h${e - x + 1}v1h${-(e - x + 1)}z`;
      x = e;
    }
  });
  return `<svg viewBox="0 0 10 10" width="20" height="20" fill="currentColor" shape-rendering="crispEdges" aria-hidden="true"><path d="${d}"/></svg>`;
};

